"""Subtle audio feedback for recording start/stop.

Two short blips (generated by packaging/make_sounds.py) played via
AppKit's NSSound: a bright one when recording starts, a lower one when it
stops. Asset path resolution is bundle-aware, mirroring flow/window.py's
_ui_dir(). NSSound instances are cached at module load so playback never
re-reads the file. Sound is cosmetic — every failure here is caught and
logged so it can never break dictation.
"""

import logging
import sys
import wave
from pathlib import Path

from .config import PROJECT_ROOT

log = logging.getLogger(__name__)

try:
    from AppKit import NSSound
except Exception:
    NSSound = None

_START_NAME = "rec_start.wav"
_STOP_NAME = "rec_stop.wav"
_HANDSFREE_NAME = "rec_handsfree.wav"

_start_sound = None
_stop_sound = None
_handsfree_sound = None
_loaded = False


def _assets_dir() -> Path:
    return Path(getattr(sys, "_MEIPASS", PROJECT_ROOT)) / "flow" / "ui" / "assets"


def _load(name: str):
    if NSSound is None:
        return None
    path = _assets_dir() / name
    try:
        return NSSound.alloc().initWithContentsOfFile_byReference_(str(path), True)
    except Exception:
        log.exception("Could not load sound asset %s", path)
        return None


def _ensure_loaded():
    global _start_sound, _stop_sound, _handsfree_sound, _loaded
    if _loaded:
        return
    _loaded = True
    _start_sound = _load(_START_NAME)
    _stop_sound = _load(_STOP_NAME)
    _handsfree_sound = _load(_HANDSFREE_NAME)
    if _start_sound is None or _stop_sound is None or _handsfree_sound is None:
        log.warning("Recording sound asset(s) missing or failed to load")


_start_duration_s = None


def _wav_duration_s(path: Path) -> float:
    try:
        with wave.open(str(path)) as w:
            return w.getnframes() / float(w.getframerate())
    except Exception:
        log.exception("Could not read the duration of %s", path)
        return 0.0


def start_duration_s() -> float:
    """Length of the start chime, read from the asset itself so it stays
    correct when packaging/make_sounds.py changes the sound design.

    The recorder uses this to mute its capture for exactly as long as the
    chime sounds — see Recorder.mute_for.
    """
    global _start_duration_s
    if _start_duration_s is None:
        _start_duration_s = _wav_duration_s(_assets_dir() / _START_NAME)
    return _start_duration_s


def play_start():
    try:
        _ensure_loaded()
        if _start_sound is not None:
            _start_sound.play()
    except Exception:
        log.exception("Failed to play start sound")


def play_stop():
    try:
        _ensure_loaded()
        if _stop_sound is not None:
            _stop_sound.play()
    except Exception:
        log.exception("Failed to play stop sound")


_handsfree_duration_s = None


def handsfree_duration_s() -> float:
    global _handsfree_duration_s
    if _handsfree_duration_s is None:
        _handsfree_duration_s = _wav_duration_s(_assets_dir() / _HANDSFREE_NAME)
    return _handsfree_duration_s


def play_handsfree():
    try:
        _ensure_loaded()
        if _handsfree_sound is not None:
            _handsfree_sound.play()
    except Exception:
        log.exception("Failed to play hands-free sound")
